"""Additional reproducible business economics and uncertainty calculations.

Inputs are explicit hypotheses, never forecasts generated by the engine.
"""
import random
import math
from decimal import Decimal
from .io import AtlasError
from .quant import D, nonnegative, probability

def ecommerce_economics(spec):
    """One-period marketplace/DTC contribution and working capital model.

    Revenue is net of included VAT; fee base is declared NET revenue.
    Returns/refunds are modeled explicitly as expected net revenue lost.
    """
    p=nonnegative(spec['price_gross']); vat=probability(spec.get('vat_rate',0)); units=nonnegative(spec['orders'])
    refund_rate=probability(spec.get('refund_rate',0))
    net=p/(1+vat); kept=net*(1-refund_rate)
    cost_keys=('unit_landed','outbound_fulfillment','payment_fixed','ads_per_order','returns_processing','other_variable')
    fixed_costs={k:nonnegative(spec.get(k,0)) for k in cost_keys}
    referral=kept*probability(spec.get('platform_fee_rate_net',0))
    payment=kept*probability(spec.get('payment_fee_rate_net',0))
    variable=sum(fixed_costs.values())+referral+payment
    margin=kept-variable
    operating_fixed=nonnegative(spec.get('period_fixed',0))
    inventory_units=nonnegative(spec.get('inventory_units',units))
    inventory_cash=inventory_units*fixed_costs['unit_landed']
    cash_before_income=nonnegative(spec.get('opening_cash',0))-inventory_cash-operating_fixed
    # Simplified when all sales are paid in same period: do not double count COGS inventory.
    settlement_fraction=probability(spec.get('settlement_fraction',1))
    collected=units*kept*settlement_fraction
    cash_after=cash_before_income+collected-units*(variable-fixed_costs['unit_landed'])
    return {'net_revenue_if_kept':str(net),'expected_net_revenue_per_order':str(kept),
            'expected_variable_cost_per_order':str(variable),'contribution_per_order':str(margin),
            'contribution_margin_on_expected_revenue':str(margin/kept) if kept else None,
            'period_operating_profit':str(margin*units-operating_fixed),
            'inventory_cash_outlay':str(inventory_cash),'illustrative_period_closing_cash':str(cash_after),
            'break_even_orders':str((operating_fixed/margin).to_integral_value(rounding='ROUND_CEILING')) if margin>0 else None,
            'warning':'Assumes refund effect and all fees as specified; exclude financing, income tax, late inventory and other delayed cash flows unless modeled separately. Not a forecast.'}

def correlated_simulation(spec):
    """Seeded Gaussian-copula Monte Carlo; matrix correlation is on latent normals.

    Unclipped normal marginals preserve population Pearson correlation. Clipping,
    finite samples and other marginals can change observed Pearson correlation.
    """
    from statistics import NormalDist
    draws=spec.get('draws',2000)
    if type(draws) is not int or not 100<=draws<=100000: raise AtlasError('draws outside 100..100000')
    if type(spec.get('seed')) is not int: raise AtlasError('Seed required')
    variables=spec.get('variables')
    if not isinstance(variables,dict) or not variables: raise AtlasError('Variables required')
    coefficients={k:float(D(v)) for k,v in spec.get('coefficients',{}).items()}
    if set(coefficients)!=set(variables): raise AtlasError('Each variable requires coefficient')
    names=list(variables); dim=len(names)
    if dim>20: raise AtlasError('Too many variables')
    matrix=spec.get('latent_correlation',[[1.0 if i==j else 0.0 for j in range(dim)] for i in range(dim)])
    if len(matrix)!=dim or any(not isinstance(row,list) or len(row)!=dim for row in matrix): raise AtlasError('Invalid correlation shape')
    corr=[[float(D(x)) for x in row] for row in matrix]
    for i in range(dim):
        for j in range(dim):
            if abs(corr[i][j]-corr[j][i])>1e-8 or abs(corr[i][j])>1: raise AtlasError('Invalid correlation matrix')
        if abs(corr[i][i]-1)>1e-8: raise AtlasError('Correlation diagonal must be one')
    # Cholesky requires positive definite (singular matrices should be modeled explicitly).
    chol=[[0.0]*dim for _ in range(dim)]
    for i in range(dim):
        for j in range(i+1):
            value=corr[i][j]-sum(chol[i][k]*chol[j][k] for k in range(j))
            if i==j:
                if value<=1e-10: raise AtlasError('Latent correlation matrix must be positive definite')
                chol[i][j]=math.sqrt(value)
            else: chol[i][j]=value/chol[j][j]
    prepared={}
    for key,dist in variables.items():
        if not isinstance(dist,dict): raise AtlasError('Distribution must be an object')
        typ=dist.get('distribution'); item={'distribution':typ}
        if typ in {'uniform','triangular'}:
            item.update(low=float(D(dist['low'])),high=float(D(dist['high'])))
            if item['high']<item['low']: raise AtlasError('Invalid distribution bounds')
            if typ=='triangular':
                item['mode']=float(D(dist['mode']))
                if not item['low']<=item['mode']<=item['high']: raise AtlasError('Invalid triangular mode')
        elif typ=='normal':
            item.update(mean=float(D(dist['mean'])),sd=float(nonnegative(dist['sd'])))
            for bound in ('low','high'):
                if bound in dist: item[bound]=float(D(dist[bound]))
            if 'low' in item and 'high' in item and item['low']>item['high']:
                raise AtlasError('Normal clipping bounds are reversed')
        elif typ=='discrete':
            pairs=dist.get('values')
            if not isinstance(pairs,list) or not pairs: raise AtlasError('Discrete values required')
            item['values']=[{'p':float(probability(row['p'])),'value':float(D(row['value']))} for row in pairs]
            if abs(sum(row['p'] for row in item['values'])-1)>1e-8: raise AtlasError('Discrete probabilities do not sum to 1')
        else: raise AtlasError('Unsupported distribution')
        prepared[key]=item
    intercept=float(D(spec.get('intercept',0)))
    rng=random.Random(spec['seed']); samples=[]
    normal=NormalDist()
    for _ in range(draws):
        eps=[rng.gauss(0,1) for _ in range(dim)]
        z=[sum(chol[i][k]*eps[k] for k in range(i+1)) for i in range(dim)]
        payoff=intercept
        for i,key in enumerate(names):
            dist=prepared[key]; typ=dist['distribution']; u=normal.cdf(z[i])
            if typ=='uniform':
                lo=dist['low']; hi=dist['high']
                draw=lo+(hi-lo)*u
            elif typ=='triangular':
                lo=dist['low']; hi=dist['high']; mode=dist['mode']
                if lo==hi: draw=lo
                elif u<(mode-lo)/(hi-lo): draw=lo+math.sqrt(u*(hi-lo)*(mode-lo))
                else: draw=hi-math.sqrt((1-u)*(hi-lo)*(hi-mode))
            elif typ=='normal':
                mu=dist['mean'];sd=dist['sd']
                draw=mu+sd*z[i]
                if 'low' in dist: draw=max(draw,dist['low'])
                if 'high' in dist: draw=min(draw,dist['high'])
            elif typ=='discrete':
                pairs=dist['values']
                cumulative=0.; draw=pairs[-1]['value']
                for row in pairs:
                    cumulative+=row['p']
                    if u<=cumulative:
                        draw=row['value'];break
            payoff+=coefficients[key]*draw
        if not math.isfinite(payoff): raise AtlasError('Nonfinite result')
        samples.append(payoff)
    samples.sort(); q=lambda x:samples[int((draws-1)*x)]
    return {'draws':draws,'seed':spec['seed'],'mean':math.fsum(samples)/draws,
            'p05':q(.05),'p50':q(.5),'p95':q(.95),'loss_probability':sum(v<0 for v in samples)/draws,
            'latent_correlation_matrix':corr,
            'warning':'Simulation conditional on declared marginals/latent Gaussian copula. Non-normal observed correlation differs from latent correlation; not forecast calibration.'}

def reverse_stress(spec):
    """Solve what acquisition expense would eliminate per-order contribution."""
    current=nonnegative(spec['current_acquisition_cost']); contribution=D(spec['contribution_per_order'])
    return {'acquisition_cost_at_zero_contribution':str(current+contribution),
            'ad_cost_increase_to_zero_contribution':str(contribution),
            'warning':'One-variable linear threshold; does not capture demand elasticity, returns, tax or competition.'}
